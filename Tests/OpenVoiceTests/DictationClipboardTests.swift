import AppKit
import XCTest
@testable import OpenVoice

@MainActor
final class DictationClipboardTests: XCTestCase {
    func testTranscriptIsMarkedTemporaryBeforePaste() {
        let board = NSPasteboard(name: NSPasteboard.Name(UUID().uuidString))
        board.clearContents()
        var typesAtPaste: [NSPasteboard.PasteboardType] = []
        var pending: [() -> Void] = []
        let inserter = ClipboardPaste(pasteboard: board,
            paste: { typesAtPaste = board.pasteboardItems?.first?.types ?? [] },
            schedule: { _, action in pending.append(action) })

        XCTAssertTrue(inserter.insert("不应进入历史的转写"))
        XCTAssertEqual(board.string(forType: .string), "不应进入历史的转写")
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                     "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertTrue(typesAtPaste.contains(NSPasteboard.PasteboardType(type)), type)
        }
        pending.removeFirst()()
        XCTAssertTrue(board.pasteboardItems?.isEmpty ?? true)
    }

    func testEmptyClipboardIsClearedAfterPaste() {
        let board = NSPasteboard(name: NSPasteboard.Name(UUID().uuidString))
        board.clearContents()
        var pasted: [String] = []
        var pending: [() -> Void] = []
        let inserter = ClipboardPaste(pasteboard: board,
            paste: { pasted.append(board.string(forType: .string) ?? "") },
            schedule: { _, action in pending.append(action) })

        XCTAssertTrue(inserter.insert("识别文字"))
        XCTAssertEqual(pasted, ["识别文字"])
        XCTAssertEqual(board.string(forType: .string), "识别文字")
        pending.removeFirst()()
        XCTAssertTrue(board.pasteboardItems?.isEmpty ?? true)
    }

    func testRapidInsertionsRestoreOriginalRichClipboard() {
        let board = NSPasteboard(name: NSPasteboard.Name(UUID().uuidString))
        let original = NSPasteboardItem()
        let customType = NSPasteboard.PasteboardType("test.openvoice.rich")
        original.setString("原内容", forType: .string)
        original.setData(Data([0, 1, 2]), forType: customType)
        board.clearContents()
        board.writeObjects([original])
        var pasted: [String] = []
        var pending: [() -> Void] = []
        let inserter = ClipboardPaste(pasteboard: board,
            paste: { pasted.append(board.string(forType: .string) ?? "") },
            schedule: { _, action in pending.append(action) })

        XCTAssertTrue(inserter.insert("第一句"))
        XCTAssertTrue(inserter.insert("第二句"))
        XCTAssertEqual(pasted, ["第一句", "第二句"])
        pending.removeFirst()()
        XCTAssertEqual(board.string(forType: .string), "第二句")
        pending.removeFirst()()
        XCTAssertEqual(board.string(forType: .string), "原内容")
        XCTAssertEqual(board.pasteboardItems?.first?.data(forType: customType), Data([0, 1, 2]))
    }

    func testNewUserCopyIsPreserved() {
        let board = NSPasteboard(name: NSPasteboard.Name(UUID().uuidString))
        board.clearContents()
        board.setString("原内容", forType: .string)
        var pending: [() -> Void] = []
        let inserter = ClipboardPaste(pasteboard: board, paste: {},
            schedule: { _, action in pending.append(action) })

        XCTAssertTrue(inserter.insert("识别文字"))
        board.clearContents()
        board.setString("用户新复制", forType: .string)
        pending.removeFirst()()
        XCTAssertEqual(board.string(forType: .string), "用户新复制")
    }
}
